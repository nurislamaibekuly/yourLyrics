  /** A CSS-style cubic-bezier(x1, y1, x2, y2) easing curve. */
  class Curve {
    constructor(x1, y1, x2, y2) {
      this.x1 = x1;
      this.y1 = y1;
      this.x2 = x2;
      this.y2 = y2;
    }

    /** Bezier polynomial evaluation for a single axis. */
    _bezier(t, p1, p2) {
      return ((1 + 3 * p1 - 3 * p2) * t + (3 * p2 - 6 * p1)) * t * t + 3 * p1 * t;
    }

    value(x) {
      let lo = 0, hi = 1;
      for (let i = 0; i < 30; i++) {
        const mid = (lo + hi) / 2;
        if (this._bezier(mid, this.x1, this.x2) < x) lo = mid;
        else hi = mid;
      }
      return this._bezier((lo + hi) / 2, this.y1, this.y2);
    }
  }

  Curve.linear = new Curve(0, 0, 1, 1);
  Curve.easeIn = new Curve(0.42, 0, 1, 1);
  Curve.easeOut = new Curve(0, 0, 0.58, 1);
  Curve.easeInOut = new Curve(0.42, 0, 0.58, 1);

  /** A damped-spring motion profile. */
  class Spring {
    constructor(stiffness = 100, damping = 10, mass = 1) {
      this.stiffness = stiffness;
      this.damping = damping;
      this.mass = mass;
    }

    value(t) {
      const omega = Math.sqrt(this.stiffness / this.mass);
      const zeta = this.damping / (2 * Math.sqrt(this.stiffness * this.mass));
      if (zeta < 1) {
        const damped = omega * Math.sqrt(1 - zeta * zeta);
        return 1 - Math.exp(-zeta * omega * t) *
          ((zeta * omega / damped) * Math.sin(damped * t) + Math.cos(damped * t));
      }
      if (zeta === 1) {
        return 1 - Math.exp(-omega * t) * (1 + omega * t);
      }
      const root = zeta + Math.sqrt(zeta * zeta - 1);
      const slow = omega / root;
      const fast = omega * root;
      return 1 - (fast * Math.exp(-slow * t) - slow * Math.exp(-fast * t)) / (fast - slow);
    }
  }

  Spring.gentle = () => new Spring(100, 20, 1);
  Spring.snappy = () => new Spring(300, 30, 0.8);
  Spring.bouncy = () => new Spring(200, 12, 1);
  Spring.smooth = () => new Spring(150, 40, 1.2);

  /**
   * Timing: tween(duration, curve) or spring(spring).
   * Mirrors ScribbleTiming from ScribbleLayout.swift.
   */
  class ScribbleTiming {
    constructor(type, duration, curve, spring) {
      this.type = type; // 'tween' | 'spring'
      this.duration = duration ?? 2;
      this.curve = curve ?? Curve.easeInOut;
      this.spring = spring ?? null;
    }

    static tween(duration = 2, curve = Curve.easeInOut) {
      return new ScribbleTiming('tween', duration, curve, null);
    }

    static spring(spring) {
      return new ScribbleTiming('spring', 0, null, spring);
    }

    static get default() {
      return ScribbleTiming.tween();
    }

    /**
     * Returns { value, isFinished } — the animated value `elapsed` seconds
     * into an animation from `from` to `to`.
     */
    sample(from, to, elapsed) {
      if (this.type === 'tween') {
        const t = this.duration > 0
          ? Math.min(Math.max(elapsed / this.duration, 0), 1)
          : 1;
        if (t >= 1) return { value: to, isFinished: true };
        return { value: from + (to - from) * this.curve.value(t), isFinished: false };
      }
      // spring
      const delta = to - from;
      const value = from + delta * this.spring.value(elapsed);
      if (!isFinite(value)) return { value: to, isFinished: true };
      const h = 1e-4;
      const before = Math.max(elapsed - h, 0);
      const velocity = delta *
        (this.spring.value(elapsed + h) - this.spring.value(before)) /
        (elapsed + h - before);
      const settled = Math.abs(to - value) <= 0.005 && Math.abs(velocity) <= 0.01;
      return { value: settled ? to : value, isFinished: settled };
    }

    /** Un-writing takes half the forward duration. */
    get rewinding() {
      if (this.type === 'tween') {
        return ScribbleTiming.tween(Math.max(0.05, this.duration / 2), this.curve);
      }
      return this;
    }
  }

